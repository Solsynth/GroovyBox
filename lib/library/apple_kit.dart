import 'dart:async';

import 'package:flutter/foundation.dart';
import 'package:music_kit/music_kit.dart';

/// What the Apple Music integration needs from the platform, behind one
/// interface.
///
/// The library layer talks to this rather than to `music_kit` directly: reads
/// are plain REST and testable off-device, and only the token/playback calls
/// reach the plugin. Tests and unsupported platforms get [SilentMusicKit].
abstract interface class MusicKitClient {
  factory MusicKitClient() => PluginMusicKit();

  /// Asks the system for permission and returns whether it was granted.
  Future<bool> requestAuthorization();

  Future<String> developerToken();

  Future<String> userToken(String developerToken);

  /// Replaces the system player's queue with [items] and starts at [startingAt].
  ///
  /// [itemType] is the resource kind the player resolves the items as: a
  /// library song is `'songs'`, a station is `'stations'`.
  Future<void> setQueue(
    List<Map<String, dynamic>> items, {
    int startingAt = 0,
    String itemType = 'songs',
  });

  Future<void> play();

  Future<void> pause();

  Future<void> stop();

  Future<void> seek(Duration position);

  Future<Duration> playbackTime();

  /// The player's own status, mapped onto the few states the app reasons about.
  Stream<ApplePlayerStatus> get status;

  /// Index of the entry the system player is on, inside the queue it was
  /// given. The system advances through its own queue, so this is how an
  /// automatic move to the next track reaches the app.
  Stream<int> get queueIndex;

  /// Moves inside the queue the platform player already holds.
  ///
  /// This is what a station needs and an app queue cannot express: a station
  /// is an endless run the system generates, so "next" there means the next
  /// track *of the station*, not the next row of the app's queue.
  Future<void> skipNext();

  Future<void> skipPrevious();

  /// The system player's whole queue, so a station's own run can be drawn.
  Stream<AppleQueue> get queue;

  /// What the system player is playing, as the resource it reports.
  ///
  /// A station has no tracklist — it generates one as it runs — so this is
  /// the only way to know which track is on the air. The entry's own title
  /// and item describe it; the outer wrapper says which queue index it is.
  Stream<AppleQueueEntry> get currentTrack;
}

/// One entry of the system player's queue, flattened to what the app shows.
///
/// A station's entries are generated by the system as it runs, so this is the
/// only description of what is actually on the air.
class AppleQueueEntry {
  const AppleQueueEntry({
    required this.id,
    this.catalogId,
    this.title,
    this.artist,
    this.album,
    this.duration = Duration.zero,
    this.artTemplate,
  });

  /// The resource id, null while the player has not resolved one yet.
  final String? id;

  /// The catalog id behind the entry, when the player resolved the track
  /// against the store rather than the account's own library. A station's
  /// tracks only exist in the catalog, and only the catalog can describe
  /// them — including their artwork.
  final String? catalogId;
  final String? title;
  final String? artist;
  final String? album;
  final Duration duration;

  /// Apple's `{w}x{h}` artwork template, when the entry carries one.
  final String? artTemplate;

  bool get isTrack => id != null && title != null;
}

/// The system player's whole queue, flattened.
class AppleQueue {
  const AppleQueue({required this.entries, required this.currentIndex});

  final List<AppleQueueEntry> entries;
  final int currentIndex;
}

/// The states of the system player the app acts on.
enum ApplePlayerStatus { stopped, playing, paused, interrupted, seeking }

/// The plugin-backed client. Only constructed on iOS and macOS 14+, which is
/// what [AppleMusicSource.isSupported] gates on.
class PluginMusicKit implements MusicKitClient {
  final MusicKit _kit = MusicKit();

  @override
  Future<bool> requestAuthorization() async {
    final status = await _kit.requestAuthorizationStatus();
    return status is MusicAuthorizationStatusAuthorized;
  }

  @override
  Future<String> developerToken() => _kit.requestDeveloperToken();

  @override
  Future<String> userToken(String developerToken) =>
      _kit.requestUserToken(developerToken);

  /// The plugin hands `startingAt` to the system as an item looked up *in*
  /// the queue; passing the first item explicitly makes MediaPlayer reject
  /// the queue ("unexpected start item"), so a start at zero is expressed by
  /// leaving it out.
  @override
  Future<void> setQueue(
    List<Map<String, dynamic>> items, {
    int startingAt = 0,
    String itemType = 'songs',
  }) => _kit.setQueueWithItems(
    itemType,
    items: items,
    startingAt: startingAt == 0 ? null : startingAt,
  );

  @override
  Future<void> play() => _kit.play();

  @override
  Future<void> pause() => _kit.pause();

  @override
  Future<void> stop() => _kit.stop();

  @override
  Future<void> seek(Duration position) => _kit.setPlaybackTime(
    position.inMicroseconds / Duration.microsecondsPerSecond,
  );

  @override
  Future<Duration> playbackTime() async {
    final seconds = await _kit.playbackTime;
    if (!seconds.isFinite || seconds < 0) return Duration.zero;
    return Duration(
      microseconds: (seconds * Duration.microsecondsPerSecond).round(),
    );
  }

  @override
  Stream<ApplePlayerStatus> get status => _kit.onMusicPlayerStateChanged.map(
    (state) => switch (state.playbackStatus) {
      MusicPlayerPlaybackStatus.playing => ApplePlayerStatus.playing,
      MusicPlayerPlaybackStatus.paused => ApplePlayerStatus.paused,
      MusicPlayerPlaybackStatus.interrupted => ApplePlayerStatus.interrupted,
      MusicPlayerPlaybackStatus.seekingBackward ||
      MusicPlayerPlaybackStatus.seekingForward => ApplePlayerStatus.seeking,
      MusicPlayerPlaybackStatus.stopped => ApplePlayerStatus.stopped,
    },
  );

  /// The entry list keeps the order it was submitted in, and `currentEntry`
  /// moves along it as tracks finish; the index is read from the entry's
  /// identity rather than its id, which the system rewrites to the catalog's.
  @override
  Stream<int> get queueIndex => _kit.onPlayerQueueChanged
      .where((queue) => queue.currentEntry != null)
      .map((queue) {
        final current = queue.currentEntry!;
        return queue.entries.indexWhere((entry) => entry.id == current.id);
      })
      .where((index) => index >= 0)
      .distinct();

  @override
  Future<void> skipNext() => _kit.skipToNextEntry();

  @override
  Future<void> skipPrevious() => _kit.skipToPreviousEntry();

  /// Every entry the system holds, in order, so a station's own run can be
  /// drawn as the queue it is.
  @override
  Stream<AppleQueue> get queue => _kit.onPlayerQueueChanged.map(
    (queue) => AppleQueue(
      entries: [for (final entry in queue.entries) _entryOfQueue(queue, entry)],
      currentIndex: queue.currentEntry == null
          ? -1
          : queue.entries.indexWhere(
              (entry) => entry.id == queue.currentEntry!.id,
            ),
    ),
  );

  @override
  Stream<AppleQueueEntry> get currentTrack => _kit.onPlayerQueueChanged
      .where((queue) => queue.currentEntry != null)
      .map((queue) => _entryOfQueue(queue, queue.currentEntry))
      // The first report describes the queue being loaded, before the player
      // has resolved a track for a station; it says nothing about what is on.
      .where((entry) => entry.id != null)
      .distinct();

  /// One entry of the system queue, flattened.
  ///
  /// Takes the entry rather than the queue: the whole list is drawn as a
  /// queue as well as the single current one being watched.
  static AppleQueueEntry _entryOfQueue(
    MusicPlayerQueue queue,
    MusicPlayerQueueEntry? current,
  ) {
    final item = current?.item;
    final attributes = item?['attributes'];
    final attrs = attributes is Map
        ? Map<String, dynamic>.from(attributes)
        : const <String, dynamic>{};
    final artwork = attrs['artwork'];
    // The artwork a station's generated track reports is a `musicKit://`
    // handle, not an image URL: the system player reads it from its own
    // cache and nothing else can. The track's catalog id is what turns it
    // back into a picture (see `AppleMusicSource.artworkUri`), so it is kept.
    final href = item?['href'];
    final catalogId = href is String
        ? RegExp(r'/songs/(\d+)$').firstMatch(href)?.group(1)
        : null;
    return AppleQueueEntry(
      id: item?['id'] == null ? null : '${item!['id']}',
      catalogId: catalogId,
      title: (attrs['name'] as String?) ?? current?.title,
      artist: attrs['artistName'] as String?,
      album: attrs['albumName'] as String?,
      duration: switch (attrs['durationInMillis']) {
        final num millis => Duration(milliseconds: millis.toInt()),
        _ => Duration.zero,
      },
      artTemplate: artwork is Map ? artwork['url'] as String? : null,
    );
  }
}

/// A client that refuses everything: a platform without MusicKit, or a test.
///
/// Returns cleanly rather than throwing, so a provider that builds it eagerly
/// cannot crash an app that never opens an Apple Music library.
class SilentMusicKit implements MusicKitClient {
  const SilentMusicKit();

  @override
  Future<bool> requestAuthorization() async => false;

  @override
  Future<String> developerToken() async => '';

  @override
  Future<String> userToken(String developerToken) async => '';

  @override
  Future<void> setQueue(
    List<Map<String, dynamic>> items, {
    int startingAt = 0,
    String itemType = 'songs',
  }) async {}

  @override
  Future<void> play() async {}

  @override
  Future<void> pause() async {}

  @override
  Future<void> stop() async {}

  @override
  Future<void> seek(Duration position) async {}

  @override
  Future<Duration> playbackTime() async => Duration.zero;

  @override
  Stream<ApplePlayerStatus> get status => const Stream.empty();

  @override
  Stream<int> get queueIndex => const Stream.empty();

  @override
  Stream<AppleQueueEntry> get currentTrack => const Stream.empty();

  @override
  Future<void> skipNext() async {}

  @override
  Future<void> skipPrevious() async {}

  @override
  Stream<AppleQueue> get queue => const Stream.empty();
}

/// Logs and swallows a platform failure the transport cannot recover from.
///
/// The player has no error surface of its own; a failed Apple Music open is
/// reported through the source failure map instead, so Settings says why the
/// provider went quiet.
void logAppleFailure(Object error) =>
    debugPrint('[AppleMusic] playback failed: $error');
